def _build_cases_table(result: SuiteResult) -> str:
    rows = []
    # 取每个 case 的第一次运行
    seen = set()
    for r in result.per_case_results:
        if r.case_id in seen:
            continue
        seen.add(r.case_id)

        score = f"{r.aggregate_score:.1f}"
        passed_cls = "pass" if r.passed else "fail"
        passed_text = "PASS" if r.passed else "FAIL"
        fc = r.failure_class.value if r.failure_class else "-"
        fc_cls = {
            "infrastructure": "fail-inf",
            "model": "fail-model",
            "test_bug": "fail-test",
        }.get(fc, "")
        cost = f"${r.cost.total_cost_usd:.4f}"
        latency = f"{r.latency_ms / 1000:.1f}s" if r.latency_ms > 0 else "-"
        meeting_id = r.meeting_id or "-"

        # Get layer scores
        l1 = r.layers.get("l1_process")
        l2 = r.layers.get("l2_internal")
        l3 = r.layers.get("l3_semantic")
        l1s = f"{l1.score * 100:.0f}" if l1 and not l1.skipped else "-"
        l2s = f"{l2.score * 100:.0f}" if l2 and not l2.skipped else "-"
        l3s = f"{l3.score * 100:.0f}" if l3 and not l3.skipped else "-"

        rows.append(f"""<tr>
          <td>{html.escape(r.case_id)}</td>
          <td class="{passed_cls}">{passed_text}</td>
          <td>{score}</td>
          <td>{l1s}</td><td>{l2s}</td><td>{l3s}</td>
          <td class="{fc_cls}">{fc}</td>
          <td>{cost}</td><td>{latency}</td>
        </tr>""")

    return f"""<table class="data-table">
      <thead><tr>
        <th>Case ID</th><th>Result</th><th>Score</th>
        <th>L1</th><th>L2</th><th>L3</th>
        <th>Failure</th><th>Cost</th><th>Latency</th>
      </tr></thead>
      <tbody>{"".join(rows)}</tbody>
    </table>"""


def _build_failures_table(result: SuiteResult) -> str:
    failed_cases = []
    for r in result.per_case_results:
        if r.run_index != 0:
            continue
        if r.passed:
            continue
        # Collect failure details
        failure_details = []
        for layer in r.layers.values():
            for f in layer.failures:
                failure_details.append(
                    f"[{layer.layer.value.replace('l', 'L').replace('_', ' ')}] {html.escape(f.detail[:200])}"
                )
        detail_text = (
            "<br>".join(failure_details[:5])
            if failure_details
            else html.escape(r.error[:200] if r.error else "No details")
        )
        fc = r.failure_class.value if r.failure_class else "unknown"
        failed_cases.append(f"""<tr>
          <td>{html.escape(r.case_id)}</td>
          <td class="fail-{fc.replace("_", "-")}">{fc}</td>
          <td>{r.aggregate_score:.1f}</td>
          <td>{detail_text}</td>
        </tr>""")

    return f"""<table class="data-table">
      <thead><tr><th>Case ID</th><th>Class</th><th>Score</th><th>Details</th></tr></thead>
      <tbody>{"".join(failed_cases) if failed_cases else '<tr><td colspan="4">No failures!</td></tr>'}</tbody>
    </table>"""


def _build_dims_table(result: SuiteResult) -> str:
    if not result.dimension_scores:
        return "<p>No dimension scores available (Judge may not be configured).</p>"

    rows = []
    for dim, score in sorted(result.dimension_scores.items()):
        pct = score * 100
        cls = "pass" if pct >= 60 else "fail"
        rows.append(f"<tr><td>{html.escape(dim)}</td><td class='{cls}'>{pct:.1f}</td></tr>")

    return f"""<table class="data-table">
      <thead><tr><th>Dimension</th><th>Score</th></tr></thead>
      <tbody>{"".join(rows)}</tbody>
    </table>"""


def _build_cost_details(result: SuiteResult) -> str:
    eff_pct = (
        f"{(result.n_cases - result.n_model_failures - result.n_infrastructure_failures) / result.n_cases * 100:.1f}%"
        if result.n_cases > 0
        else "-"
    )
    return f"""<div class="info-grid">
      <div class="info-item"><span class="info-label">Total Cost</span><span class="info-value">${result.total_cost_usd:.4f}</span></div>
      <div class="info-item"><span class="info-label">SUT Cost</span><span class="info-value">${result.total_cost_usd - result.judge_cost_usd:.4f}</span></div>
      <div class="info-item"><span class="info-label">Judge Cost</span><span class="info-value">${result.judge_cost_usd:.4f}</span></div>
      <div class="info-item"><span class="info-label">Cost Per Pass</span><span class="info-value">${result.cost_per_pass:.4f}</span></div>
      <div class="info-item"><span class="info-label">Total Tokens</span><span class="info-value">{result.total_tokens:,}</span></div>
      <div class="info-item"><span class="info-label">Pass Rate</span><span class="info-value">{eff_pct}</span></div>
    </div>"""


def _build_ablation_details(result: SuiteResult) -> str:
    if not result.ablation:
        return "<p>No ablation data.</p>"
    ab = result.ablation
    sig = "YES" if ab.is_significant else "NO"
    return f"""<div class="info-grid">
      <div class="info-item"><span class="info-label">Multi-Agent Score</span><span class="info-value">{ab.multi_agent_score * 100:.1f}</span></div>
      <div class="info-item"><span class="info-label">Direct LLM Score</span><span class="info-value">{ab.direct_llm_score * 100:.1f}</span></div>
      <div class="info-item"><span class="info-label">Uplift</span><span class="info-value">{ab.uplift * 100:+.1f}pp</span></div>
      <div class="info-item"><span class="info-label">Pairwise Win Rate</span><span class="info-value">{ab.pairwise_win_rate:.1%} ({ab.pairwise_wins}W/{ab.pairwise_losses}L/{ab.pairwise_ties}T)</span></div>
      <div class="info-item"><span class="info-label">p-value</span><span class="info-value">{ab.p_value:.4f}</span></div>
      <div class="info-item"><span class="info-label">Significant</span><span class="info-value">{sig}</span></div>
      <div class="info-item"><span class="info-label">Cost Ratio</span><span class="info-value">{ab.cost_ratio:.1f}x</span></div>
    </div>"""


def _build_model_info(result: SuiteResult) -> str:
    mi = result.model_info
    same_fam = ' <span class="warning-badge">SAME FAMILY</span>' if mi.is_same_family else ""
    return f"""<div class="model-info">
      Target: <strong>{html.escape(mi.model or "unknown")}</strong> @ {html.escape(mi.provider or "unknown")} |
      Judge: <strong>{html.escape(mi.judge_model or "unknown")}</strong>{same_fam}
    </div>"""


def _build_warnings(result: SuiteResult) -> str:
    warnings = []
    if result.model_info.is_same_family:
        warnings.append("Judge model is same family as target model - results may have self-evaluation bias.")
    if result.length_bias_pearson_r is not None and abs(result.length_bias_pearson_r) > 0.7:
        warnings.append(
            f"Length bias detected (Pearson r = {result.length_bias_pearson_r:.3f}) - longer artifacts tend to score higher."
        )
    if result.judge_unreliable_count > 0:
        warnings.append(f"{result.judge_unreliable_count} unreliable Judge ratings (high variance across runs).")
    if result.n_infrastructure_failures > 0:
        warnings.append(
            f"{result.n_infrastructure_failures} infrastructure failures detected - these are NOT model failures."
        )
    if not warnings:
        return ""
    items = "".join(f"<li>{html.escape(w)}</li>" for w in warnings)
    return f'<div class="warnings"><ul>{items}</ul></div>'


